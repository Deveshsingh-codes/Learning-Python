#File IO Basic
"r"  # open file for reading ----Default----
"w" # open file for writing
"a" # open file for appending at the end of the file
"x" # open file for exclusive creation, if the file already exists, the operation will fail                                     
"t" # open file in text mode ----Default----
"b" # open file in binary mode
"+" # open file for updating (reading and writing)  


